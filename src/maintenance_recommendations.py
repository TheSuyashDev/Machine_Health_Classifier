# ─────────────────────────────────────────────────────────────────────────────
# 2. DATA STRUCTURE
# ─────────────────────────────────────────────────────────────────────────────

@dataclass
class MaintenanceRecommendation:
    """
    Structured actionable maintenance advice for a CNC machine.

    Attributes
    ----------
    machine_id           : Identifier of the evaluated machine
    predicted_condition  : "Normal", "Warning", or "Critical"
    urgency_level        : "ROUTINE", "SCHEDULED", or "IMMEDIATE"
    time_horizon         : Recommended deadline for intervention
    primary_action       : High-level tactical directive
    supporting_evidence  : Specific sensor readings/flags justifying the action
    action_checklist     : Step-by-step procedures for the technician
    neighbor_context     : Corroborating evidence from historical similar machines
    disclaimer           : Standard safety and operational caveat
    """
    machine_id: str
    predicted_condition: str
    urgency_level: str
    time_horizon: str
    primary_action: str
    supporting_evidence: list[str]
    action_checklist: list[str]
    neighbor_context: str
    disclaimer: str = SAFETY_DISCLAIMER


# ─────────────────────────────────────────────────────────────────────────────
# 3. EVIDENCE EXTRACTION ENGINE
# ─────────────────────────────────────────────────────────────────────────────

def extract_sensor_evidence(
    record: dict | pd.Series,
    thresholds: Optional[dict[str, float]] = None,
) -> list[str]:
    """
    Analyze raw machine telemetry to extract specific physical anomalies.

    Parameters
    ----------
    record     : Dictionary or Series of machine features.
    thresholds : Optional custom threshold overrides.

    Returns
    -------
    List of human-readable diagnostic evidence bullets.
    """
    th = copy.deepcopy(DEFAULT_DIAGNOSTIC_THRESHOLDS)
    if thresholds:
        th.update(thresholds)

    evidence: list[str] = []

    # 1. Vibration
    vib = record.get("vibration_mm_s")
    if vib is not None and not pd.isna(vib):
        vib_val = float(vib)
        if vib_val >= th["vibration_critical_mm_s"]:
            evidence.append(f"Severe Vibration: {vib_val:.2f} mm/s (CRITICAL limit: {th['vibration_critical_mm_s']:.1f} mm/s)")
        elif vib_val >= th["vibration_warning_mm_s"]:
            evidence.append(f"Elevated Vibration: {vib_val:.2f} mm/s (Warning threshold: {th['vibration_warning_mm_s']:.1f} mm/s)")

    # 2. Spindle Temperature
    temp = record.get("operating_temp_c")
    if temp is not None and not pd.isna(temp):
        temp_val = float(temp)
        if temp_val >= th["temp_critical_c"]:
            evidence.append(f"Spindle Overheating: {temp_val:.1f} °C (CRITICAL limit: {th['temp_critical_c']:.1f} °C)")
        elif temp_val >= th["temp_warning_c"]:
            evidence.append(f"Elevated Spindle Temp: {temp_val:.1f} °C (Warning threshold: {th['temp_warning_c']:.1f} °C)")

    # 3. Coolant System
    cool_fail = record.get("coolant_failure")
    if cool_fail is not None and not pd.isna(cool_fail) and int(cool_fail) == 1:
        evidence.append("Active Fault: Coolant delivery system failure detected (Asymmetric alarm)")

    cool_temp = record.get("coolant_temp_c")
    if cool_temp is not None and not pd.isna(cool_temp):
        cool_temp_val = float(cool_temp)
        if cool_temp_val >= th["coolant_temp_critical_c"]:
            evidence.append(f"Coolant Overheating: {cool_temp_val:.1f} °C (Critical: {th['coolant_temp_critical_c']:.1f} °C)")
        elif cool_temp_val >= th["coolant_temp_warning_c"]:
            evidence.append(f"Elevated Coolant Temp: {cool_temp_val:.1f} °C (Warning: {th['coolant_temp_warning_c']:.1f} °C)")

    # 4. Tool & Component Wear
    wear = record.get("wear_level")
    if wear == "Critical":
        evidence.append("Tool Wear Level: Critical (Tool replacement required immediately)")
    elif wear == "High":
        evidence.append("Tool Wear Level: High (Approaching end of tool life)")

    deg = record.get("degradation_level")
    if deg == "Severe":
        evidence.append("Structural Degradation: Severe structural/mechanical wear logged")
    elif deg == "Moderate":
        evidence.append("Structural Degradation: Moderate wear on guide-ways/bearings")

    # 5. Acoustic & Lubrication Alarms
    noise = record.get("abnormal_noise")
    if noise is not None and not pd.isna(noise) and int(noise) == 1:
        evidence.append("Acoustic Sensor: Abnormal mechanical chatter / grinding noise registered")

    lube = record.get("lubrication_alert")
    if lube is not None and not pd.isna(lube) and int(lube) == 1:
        evidence.append("Lubrication Alarm: Lubricant pressure/level alert triggered")

    # 6. Maintenance History
    overdue = record.get("maintenance_overdue")
    if overdue is not None and not pd.isna(overdue) and int(overdue) == 1:
        evidence.append("Compliance: Scheduled maintenance is overdue")

    maint_cond = record.get("maintenance_condition")
    if maint_cond == "Poor":
        evidence.append("Service History: Previous maintenance condition rated as 'Poor'")

    last_days = record.get("last_maintenance_days")
    if last_days is not None and not pd.isna(last_days) and float(last_days) >= th["maintenance_overdue_days"]:
        evidence.append(f"Time Since Service: {float(last_days):.0f} days since last physical maintenance")

    if not evidence:
        evidence.append("All physical parameters, thermal readings, and alarm sensors within normal limits.")

    return evidence


# ─────────────────────────────────────────────────────────────────────────────
# 4. NEIGHBOR HISTORICAL CONTEXT
# ─────────────────────────────────────────────────────────────────────────────

def summarize_neighbor_history(neighbor_df: Optional[pd.DataFrame]) -> str:
    """
    Summarize empirical maintenance context from nearest historical neighbors.
    """
    if neighbor_df is None or len(neighbor_df) == 0:
        return "No historical nearest neighbor context available."

    n_total = len(neighbor_df)
    conditions = neighbor_df["condition"].value_counts().to_dict()
    cond_str = ", ".join(f"{cnt} {cond}" for cond, cnt in conditions.items())

    # Check common fault patterns in nearest neighbors
    patterns = []
    if "coolant_failure" in neighbor_df.columns:
        cf_count = (neighbor_df["coolant_failure"] == 1).sum()
        if cf_count > 0:
            patterns.append(f"{cf_count}/{n_total} neighbors had coolant failure")

    if "abnormal_noise" in neighbor_df.columns:
        noise_count = (neighbor_df["abnormal_noise"] == 1).sum()
        if noise_count > 0:
            patterns.append(f"{noise_count}/{n_total} neighbors exhibited abnormal noise")

    pattern_text = f" (Key historical patterns: {'; '.join(patterns)})" if patterns else ""
    top_neighbor = neighbor_df.iloc[0]
    top_sim = top_neighbor.get("similarity", 0.0)
    top_id  = top_neighbor.get("machine_id", "N/A")
    top_c   = top_neighbor.get("condition", "N/A")

    return (
        f"Corroborated by {n_total} most similar machines in historical database: {cond_str}. "
        f"Closest match was {top_id} (Similarity: {top_sim:.4f}, Condition: {top_c}){pattern_text}."
    )


# ─────────────────────────────────────────────────────────────────────────────
# 5. RECOMMENDATION GENERATION
# ─────────────────────────────────────────────────────────────────────────────

def generate_recommendation(
    predicted_condition: str,
    machine_record: dict | pd.Series,
    neighbor_df: Optional[pd.DataFrame] = None,
    custom_policy: Optional[dict[str, dict[str, Any]]] = None,
    custom_thresholds: Optional[dict[str, float]] = None,
) -> MaintenanceRecommendation:
    """
    Map predicted health state and sensor telemetry to concrete maintenance guidance.

    Parameters
    ----------
    predicted_condition : "Normal", "Warning", or "Critical"
    machine_record      : Machine telemetry row (dict or Series)
    neighbor_df         : Optional DataFrame of top-k neighbors from classifier
    custom_policy       : Optional override for maintenance SOP policy
    custom_thresholds   : Optional override for sensor diagnostic limits

    Returns
    -------
    MaintenanceRecommendation dataclass instance.
    """
    valid_conditions = ["Normal", "Warning", "Critical"]
    if predicted_condition not in valid_conditions:
        raise ValueError(
            f"Unknown condition '{predicted_condition}'. Expected one of {valid_conditions}"
        )

    # 1. Resolve policy
    policy_dict = copy.deepcopy(DEFAULT_MAINTENANCE_POLICY)
    if custom_policy:
        for k, v in custom_policy.items():
            if k in policy_dict:
                policy_dict[k].update(v)

    p_info = policy_dict[predicted_condition]

    # 2. Extract sensor evidence
    evidence = extract_sensor_evidence(machine_record, custom_thresholds)

    # 3. Compile technician checklist tailored to evidence
    checklist = list(p_info["standard_checklist"])
    # Dynamic checklist injection based on evidence
    rec_dict = machine_record.to_dict() if isinstance(machine_record, pd.Series) else machine_record
    if rec_dict.get("coolant_failure") == 1 or rec_dict.get("coolant_failure") == 1.0:
        checklist.insert(0, "[CRITICAL CHECK] Inspect coolant pump impeller, supply lines, and filter mesh.")
    if rec_dict.get("wear_level") in ("Critical", "High"):
        checklist.insert(1, "[TOOLING CHECK] Remove and inspect cutting tool insert; re-zero tool offset.")
    if rec_dict.get("lubrication_alert") == 1 or rec_dict.get("lubrication_alert") == 1.0:
        checklist.append("[LUBRICATION] Check central grease reservoir level and purge manifold air.")

    # 4. Context from neighbors
    neighbor_context = summarize_neighbor_history(neighbor_df)
    machine_id = str(rec_dict.get("machine_id", "NEW_MACHINE"))

    return MaintenanceRecommendation(
        machine_id          = machine_id,
        predicted_condition = predicted_condition,
        urgency_level       = p_info["urgency_level"],
        time_horizon        = p_info["time_horizon"],
        primary_action      = p_info["primary_action"],
        supporting_evidence = evidence,
        action_checklist    = checklist,
        neighbor_context    = neighbor_context,
    )


# ─────────────────────────────────────────────────────────────────────────────
# 6. FORMATTING UTILITY
# ─────────────────────────────────────────────────────────────────────────────

def format_recommendation(reco: MaintenanceRecommendation) -> str:
    """
    Format a MaintenanceRecommendation into an industrial work-order style report.
    """
    urgency_badge = f"[{reco.urgency_level}]"
    lines = []
    lines.append("\n" + "=" * 70)
    lines.append(f"  PREDICTIVE MAINTENANCE WORK-ORDER ADVICE: MACHINE {reco.machine_id}")
    lines.append("=" * 70)
    lines.append(f"  Health Condition : {reco.predicted_condition.upper()}")
    lines.append(f"  Action Urgency   : {urgency_badge:<12} (Timeline: {reco.time_horizon})")
    lines.append(f"  Primary Directive: {reco.primary_action}")

    lines.append("\n  Diagnostic Physical Evidence:")
    for ev in reco.supporting_evidence:
        lines.append(f"    * {ev}")

    lines.append("\n  Recommended Maintenance Checklist:")
    for idx, step in enumerate(reco.action_checklist, 1):
        lines.append(f"    [ ] Step {idx}: {step}")

    lines.append("\n  Historical Corroboration:")
    lines.append(f"    {reco.neighbor_context}")

    lines.append("\n  Safety Caveat:")
    lines.append(f"    {reco.disclaimer}")
    lines.append("=" * 70 + "\n")

    return "\n".join(lines)


